export const VISIBILITY_THRESHOLD = 0.5;

export const isVisible = (landmark, min = VISIBILITY_THRESHOLD) => {
  if (!landmark) {
    return false;
  }

  const score = landmark.visibility ?? landmark.presence ?? 1;
  return score >= min;
};

export const getLandmark = (landmarks, index) =>
  Array.isArray(landmarks) ? landmarks[index] : undefined;

export const midpoint = (a, b) => {
  if (!a || !b) {
    return null;
  }

  return {
    x: (a.x + b.x) / 2,
    y: (a.y + b.y) / 2,
    z: ((a.z ?? 0) + (b.z ?? 0)) / 2,
    visibility: Math.min(a.visibility ?? 1, b.visibility ?? 1),
  };
};
